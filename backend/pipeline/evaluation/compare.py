"""Compare a generated workbook with a reference workbook, field by field.

Rows are not compared by position: the pipeline and the reference author order and name things
differently. Each table (two-level sheets split into one table per level) is aligned first,
pairing rows by the similarity of their content, with a small preference for the same relative
position. Entity names are then mapped through the aligned pairs, so a reference written with
generated names ("E1", "Visit 1") is compared with the reference author's names by what it points
at, not by spelling.

Every cell is scored by tier (Phase 0 decision: tiered scoring):

- code: controlled terminology resolved to C-codes on both sides (a submission value, preferred
  term, synonym or C-code written in either workbook counts as the same term);
- reference: names of other entities, mapped through the alignment;
- value: formatted values normalised (numbers, units and their plurals, booleans, dates);
- text: prose, matched when its fuzzy similarity reaches `TEXT_MATCH` after markup is stripped;
- identifier: the entity's own name, generated by code; reported but not in the headline.

A field is a non-empty cell, or one item of a multi-valued cell, so every schedule mark and every
characteristic counts on its own. Unaligned reference rows count as missing, unaligned generated
rows as extra.
"""

